"""Generate synthesis/capability-matrix.md from projects/*/facts.yaml.

The matrix is derived, never hand-edited. Hand-maintaining it guarantees drift
from the teardowns by about project four.

    ./.venv/bin/python tools/build_matrix.py

Writes synthesis/capability-matrix.md. Rows are the capability lines defined in
CAPABILITIES below; each maps to the probe that decides it.
"""

